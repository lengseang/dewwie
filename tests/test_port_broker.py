#!/usr/bin/env python3
"""
SwarmHerd Port Broker Unit Test Suite.

Verifies PortBroker mechanics:
  1. Base port slots: Web (3000), API (8000), Vite (5173) + (slot * offset)
  2. TCP collision detection: Skips already-bound ports and finds open ones
  3. Environment file generation: .env.local injection formatting
"""

import os
import sys
import socket
import tempfile
import unittest
from typing import Dict, List, Optional

DEFAULT_BASE_PORTS = {
    "web": 3000,
    "api": 8000,
    "vite": 5173
}

class PortBroker:
    """Port broker logic aligning with the Rust core-daemon implementation."""
    def __init__(self, base_ports: Optional[Dict[str, int]] = None, slot_offset: int = 10):
        self.base_ports = base_ports or DEFAULT_BASE_PORTS.copy()
        self.slot_offset = slot_offset

    def is_port_available(self, port: int, host: str = "127.0.0.1") -> bool:
        """Check if TCP port is available to bind."""
        # 1. Check if something is actively listening
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.settimeout(0.1)
            if probe.connect_ex((host, port)) == 0:
                return False

        # 2. Try binding without SO_REUSEADDR on Windows
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                if sys.platform != "win32":
                    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                s.bind((host, port))
                return True
        except OSError:
            return False

    def allocate_ports_for_slot(self, slot: int, host: str = "127.0.0.1") -> Dict[str, int]:
        """Allocate available ports for a given workspace slot index."""
        allocations = {}
        for service, base in self.base_ports.items():
            candidate = base + (slot * self.slot_offset)
            # Find next free port starting from candidate
            while candidate < 65535:
                if self.is_port_available(candidate, host):
                    allocations[service] = candidate
                    break
                candidate += 1
            if service not in allocations:
                raise RuntimeError(f"Failed to find free port for service {service}")
        return allocations

    def write_env_local(self, target_dir: str, ports: Dict[str, int]) -> str:
        """Inject allocated ports into .env.local inside the worktree."""
        os.makedirs(target_dir, exist_ok=True)
        env_path = os.path.join(target_dir, ".env.local")
        lines = [
            "# Auto-generated by SwarmHerd Port Broker",
            f"PORT={ports.get('web', 3000)}",
            f"API_PORT={ports.get('api', 8000)}",
            f"VITE_PORT={ports.get('vite', 5173)}",
            f"SWARMHERD_SLOT_PORTS=\"{','.join(f'{k}:{v}' for k, v in ports.items())}\"",
            ""
        ]
        with open(env_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        return env_path

class TestPortBroker(unittest.TestCase):
    def setUp(self):
        self.broker = PortBroker()
        self.temp_dir = tempfile.mkdtemp(prefix="swarmherd_port_test_")

    def tearDown(self):
        import shutil
        shutil.rmtree(self.temp_dir, ignore_errors=True)

    def test_slot_0_allocation(self):
        ports = self.broker.allocate_ports_for_slot(0)
        self.assertIn("web", ports)
        self.assertIn("api", ports)
        self.assertIn("vite", ports)
        self.assertGreaterEqual(ports["web"], 3000)
        self.assertGreaterEqual(ports["api"], 8000)
        self.assertGreaterEqual(ports["vite"], 5173)

    def test_slot_increment_offset(self):
        ports_0 = self.broker.allocate_ports_for_slot(0)
        ports_1 = self.broker.allocate_ports_for_slot(1)
        ports_2 = self.broker.allocate_ports_for_slot(2)

        # Slot 1 should have higher ports than Slot 0
        self.assertGreater(ports_1["web"], ports_0["web"])
        self.assertGreater(ports_2["web"], ports_1["web"])

    def test_collision_detection_and_skip(self):
        # Deliberately occupy port 3020
        target_port = 3020
        srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            srv.bind(("127.0.0.1", target_port))
            srv.listen(1)

            # Check that is_port_available correctly reports False
            self.assertFalse(self.broker.is_port_available(target_port))

            # Broker allocating slot 2 (base 3000 + 20 = 3020) should skip 3020 and pick 3021+
            ports = self.broker.allocate_ports_for_slot(2)
            self.assertNotEqual(ports["web"], target_port)
            self.assertGreater(ports["web"], target_port)
        finally:
            srv.close()

    def test_env_local_injection(self):
        ports = {"web": 3010, "api": 8010, "vite": 5183}
        env_file = self.broker.write_env_local(self.temp_dir, ports)
        self.assertTrue(os.path.exists(env_file))

        with open(env_file, "r", encoding="utf-8") as f:
            content = f.read()

        self.assertIn("PORT=3010", content)
        self.assertIn("API_PORT=8010", content)
        self.assertIn("VITE_PORT=5183", content)
        self.assertIn("SWARMHERD_SLOT_PORTS=", content)

if __name__ == "__main__":
    unittest.main()
